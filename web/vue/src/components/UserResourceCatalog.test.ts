it('reloads a conflicted personal editor only after discarding is confirmed, then requires a new save',async()=>{
 api.personal.mockResolvedValue({items:[own]});api.savePersonal.mockRejectedValueOnce(Object.assign(new Error('RESOURCE_GENERATION_CHANGED'),{status:409})).mockResolvedValue({...own,generation:5})
 render(h(UserResourceCatalog,{mode:'library'}))
 await fireEvent.click(await screen.findByRole('button',{name:'编辑 我的衔接'}))
 await fireEvent.update(screen.getByLabelText('资源名称'),'我未保存的名称')
 await fireEvent.click(screen.getByRole('button',{name:'保存为我的版本'}))
 await screen.findByRole('alert')
 await fireEvent.click(screen.getByRole('button',{name:'重新载入最新版本'}))
 await fireEvent.click(screen.getByRole('button',{name:'保留当前修改'}))
 expect((screen.getByLabelText('资源名称') as HTMLInputElement).value).toBe('我未保存的名称')
 expect(api.personal).toHaveBeenCalledTimes(1)
 api.personal.mockResolvedValue({items:[{...own,generation:4,name:'另一页的新名称'}]})
 await fireEvent.click(screen.getByRole('button',{name:'重新载入最新版本'}))
 await fireEvent.click(screen.getByRole('button',{name:'放弃修改并重新载入'}))
 expect(await screen.findByDisplayValue('另一页的新名称')).toBeTruthy()
 expect(api.savePersonal).toHaveBeenCalledTimes(1)
 await fireEvent.click(screen.getByRole('button',{name:'保存为我的版本'}))
 await waitFor(()=>expect(api.savePersonal).toHaveBeenLastCalledWith('mine',expect.objectContaining({expected_generation:4,name:'另一页的新名称'})))
})
