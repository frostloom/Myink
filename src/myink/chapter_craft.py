CRAFT_LESSON = """【落笔方法：把要求变成读者能看见的文字】
先让读者定位谁在何处、对着什么做事，再分配描述。动作中的施力对象、先后和空间关系要能跟得上；抽象气氛如果没有落到可感知后果，换成现场真正改变的东西。
选择细节：同一物件可以交代职业、处境或关系，优先写人物此刻会注意且对选择有影响的部分。不要为了“展示”增加无关小动作；有新信息的心理叙述可以直写。
视角距离：沿用作品视角与人物可知范围。紧张场面可贴近感官和当下判断，转场或交代可适度拉远；移动距离要有语境，不忽然跳进别人的内心替其解释。
对白先有诉求与压力，再有措辞。让人物分别依赖规程、亲历、利益或感情说服对方；称呼、避答和让步也能显出关系，不靠每人一句口头禅。双方都知道的事，不安排成互相讲课。
句段节奏由信息与情绪决定。用较紧的句子承载关键变化，用较舒展的句段让判断或感受展开；别持续堆单句段，也别把每段结尾写成结论或金句。修辞只解决眼前感受，不替代场面。
对照例（仅示范手法，不搬事实）：空泛说明“她担心他付不起钱”，可改成“她把账单翻过去，问他吃过饭没有”，让遮掩动作与避开的问话承载关心；若人物本来坦率，直接问也合理。不要把例子的账单、动作或人名复制进无关场景。
修改时先校对事实与承接，再处理人物声音和句段。保留有作用的笨拙、重复和留白，不按禁词数量或所谓AI概率改稿，也不为文笔升级凭空加设定。"""
